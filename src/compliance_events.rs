//! The provider's own verdict on every message we send (2026-11-22).
//!
//! WHY THIS EXISTS. `email_suppressions` is this app's do-not-mail list: the gate in
//! `email_provider::send` honours it, the public opt-out page writes to it, and the operator's
//! console can add and remove rows. What was missing was the one source that fills it WITHOUT a
//! human noticing something went wrong: the provider's delivery events. Measured on this account
//! (2026-11-22), `GET /v3/domains/<domain>/webhooks` answered `{}` for this app's mail domain — so a
//! hard bounce or a spam complaint was reported to NOBODY, the address stayed unsuppressed, and the
//! next notice mailed a dead mailbox again. That is the fastest way to damage the sending domain,
//! which is a shared asset: when it is throttled, a customer's password-reset stops arriving.
//!
//! TWO RULES, both taken from the sibling apps' receivers (CoreSwift `mail_compliance/webhook`,
//! FunnelSwift `compliance_events`):
//!  1. The endpoint has no session, so the credential is IN THE PATH: a secret this app generates
//!     (48 hex chars) and stores in `admin_settings.mailgun_events_token`. It is compared in
//!     constant time; a wrong token is a 403 that writes nothing. A URL token is used INSTEAD of a
//!     signature because Mailgun's account-level webhook signing key is not the API credential this
//!     app holds (measured on this account 2026-11-19), so an HMAC check would refuse every real
//!     delivery.
//!  2. An event is attributed to an address this app owns (`users` first, then `leads`). An address
//!     no workspace owns is acknowledged and ignored — the provider is not told who our customers
//!     are.
//!
//! WHY THE PLATFORM SCOPE. This app mails as ITSELF — one brand, one sending domain — and its
//! sender consults `email_suppressions` under [`PLATFORM_TENANT`] (`email_provider.rs`). A row
//! written under any other tenant would be a suppression the sender never reads: the mechanism
//! would exist while the population never matched. So the event writes exactly the row the gate
//! reads.
//!
//! WHAT IT RECORDS, all through `compliance::suppress` so the row is identical to one the operator
//! or the opt-out page would write:
//!  * `failed` with severity `permanent`, or `rejected`  -> reason `hard_bounce`, class `all`
//!  * `complained`                                        -> reason `complaint`,  class `all`
//!  * `unsubscribed`                                      -> reason `unsubscribed`, class `all`
//!
//! A temporary failure suppresses NOTHING (a full mailbox is not a dead one), and `delivered` is
//! ignored here. Both body shapes are accepted: Mailgun's webhook POST (`{"event-data": {...}}`),
//! the events-API item (`{...}`) and a JSON array of items, so the same endpoint can be replayed
//! from a shell.

use axum::{
    body::Bytes,
    extract::{Path, State},
    http::StatusCode,
    response::{IntoResponse, Json, Response},
};
use serde_json::{json, Value};
use sqlx::PgPool;

use crate::auth::middleware::AuthUser;
use crate::compliance::PLATFORM_TENANT;
use crate::state::AppState;

/// `admin_settings` key holding the secret carried in the webhook URL.
const TOKEN_KEY: &str = "mailgun_events_token";

/// The host the provider must reach. Same constant the mail templates link to, so a URL the
/// console prints and a URL a customer clicks can never disagree about which install this is.
const APP_URL: &str = "https://app.incentiveswift.com";

fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

fn refusal(status: StatusCode, message: &str) -> Response {
    (status, Json(json!({ "error": message }))).into_response()
}

/// The webhook token, created on first use.
///
/// Created lazily rather than shipped in a migration so a fresh install has no shared secret in the
/// repository: the first caller (the operator reading the URL, or a real event) mints it, and
/// `ON CONFLICT DO NOTHING` makes two concurrent callers agree on one value.
pub async fn token(pool: &PgPool) -> Result<String, sqlx::Error> {
    if let Some(existing) =
        sqlx::query_scalar::<_, String>("SELECT value #>> '{}' FROM admin_settings WHERE key = $1")
            .bind(TOKEN_KEY)
            .fetch_optional(pool)
            .await?
    {
        if !existing.trim().is_empty() {
            return Ok(existing);
        }
    }
    let fresh = format!(
        "{}{}",
        uuid::Uuid::new_v4().simple(),
        uuid::Uuid::new_v4().simple()
    );
    sqlx::query(
        "INSERT INTO admin_settings (key, value, description, updated_at)
         VALUES ($1, to_jsonb($2::text), 'Secret carried in the mail-provider events webhook URL (generated by the app)', NOW())
         ON CONFLICT (key) DO NOTHING",
    )
    .bind(TOKEN_KEY)
    .bind(&fresh)
    .execute(pool)
    .await?;
    sqlx::query_scalar::<_, String>("SELECT value #>> '{}' FROM admin_settings WHERE key = $1")
        .bind(TOKEN_KEY)
        .fetch_one(pool)
        .await
}

/// POST /api/v1/webhooks/mailgun/events/:token — the provider's delivery events.
pub async fn events_webhook(
    State(state): State<AppState>,
    Path(supplied): Path<String>,
    body: Bytes,
) -> Response {
    let pool = &state.pool;
    let expected = match token(pool).await {
        Ok(t) => t,
        Err(e) => {
            tracing::error!("could not read the mail-events token: {e}");
            return refusal(
                StatusCode::INTERNAL_SERVER_ERROR,
                "could not read the events token",
            );
        }
    };
    if !constant_time_eq(expected.as_bytes(), supplied.as_bytes()) {
        tracing::warn!("mail events refused — the URL token does not match");
        return refusal(StatusCode::FORBIDDEN, "unknown mail-events endpoint");
    }

    let parsed: Value = match serde_json::from_slice(&body) {
        Ok(v) => v,
        Err(e) => return refusal(StatusCode::BAD_REQUEST, &format!("expected JSON: {e}")),
    };

    // One POST may carry one event (the webhook shape, wrapped in `event-data`), a bare event (the
    // events-API shape) or a batch (an array) — the same code path for all three.
    let items: Vec<&Value> = match &parsed {
        Value::Array(list) => list.iter().collect(),
        Value::Object(map) => match map.get("event-data") {
            Some(inner) => vec![inner],
            None => vec![&parsed],
        },
        _ => return refusal(StatusCode::BAD_REQUEST, "expected an event object"),
    };

    let mut recorded = 0usize;
    let mut ignored = 0usize;
    for item in items {
        let event = item.get("event").and_then(Value::as_str).unwrap_or("");
        let severity = item.get("severity").and_then(Value::as_str).unwrap_or("");
        let reason = match (event, severity) {
            ("failed", "permanent") | ("rejected", _) => "hard_bounce",
            ("complained", _) => "complaint",
            ("unsubscribed", _) => "unsubscribed",
            _ => {
                ignored += 1;
                continue;
            }
        };
        let Some(address) = recipient(item) else {
            ignored += 1;
            continue;
        };
        if !owned_address(pool, &address).await {
            // A real bounce for an address this app never mails is not ours to record;
            // acknowledging it keeps the provider from retrying a delivery we will never act on.
            tracing::info!(address = %address, event = %event, "mail event ignored — no workspace owns the address");
            ignored += 1;
            continue;
        }
        match crate::compliance::suppress(
            pool,
            PLATFORM_TENANT,
            &address,
            reason,
            "all",
            "provider_event",
        )
        .await
        {
            Ok(()) => {
                recorded += 1;
                tracing::info!(
                    address = %address,
                    reason = %reason,
                    "mail event recorded — address suppressed"
                );
            }
            Err(e) => {
                tracing::error!(address = %address, error = %e, "mail event could not be recorded");
                return refusal(
                    StatusCode::INTERNAL_SERVER_ERROR,
                    &format!("could not record the event: {e}"),
                );
            }
        }
    }

    // The path just proved itself: the provider reached us with a real payload. Record WHEN, so the
    // console can tell the operator the safety net is live instead of asking them to paste a URL into
    // a provider they do not control (`webhook_url` reads this back).
    record_receipt(pool, recorded, ignored).await;

    Json(json!({ "recorded": recorded, "ignored": ignored })).into_response()
}

/// The last verified delivery report this installation received (`admin_settings.mail_events_last`).
///
/// Written for EVERY verified POST, including one that suppresses nothing: the fact worth showing is
/// that the provider's events reach this app at all. A write failure never fails the event.
async fn record_receipt(pool: &PgPool, recorded: usize, ignored: usize) {
    let payload = json!({
        "at": chrono::Utc::now().to_rfc3339(),
        "recorded": recorded,
        "ignored": ignored,
    });
    if let Err(e) = sqlx::query(
        "INSERT INTO admin_settings (key, value, description, updated_at)
         VALUES ('mail_events_last', $1, 'The last delivery report the mail provider posted to this installation (written by the events receiver)', NOW())
         ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW()",
    )
    .bind(payload)
    .execute(pool)
    .await
    {
        tracing::warn!("could not record the last mail event: {e}");
    }
}

/// The address an event is about, in either provider shape.
fn recipient(item: &Value) -> Option<String> {
    let raw = item
        .get("recipient")
        .and_then(Value::as_str)
        .map(str::to_string)
        .or_else(|| {
            item.get("message")
                .and_then(|m| m.get("headers"))
                .and_then(|h| h.get("to"))
                .and_then(Value::as_str)
                .map(str::to_string)
        })?;
    // `"Name <a@b.c>"` and a bare address are both possible; the list stores the address.
    let trimmed = raw.trim();
    let address = match (trimmed.rfind('<'), trimmed.rfind('>')) {
        (Some(open), Some(close)) if close > open => &trimmed[open + 1..close],
        _ => trimmed,
    };
    let address = address.trim();
    if address.contains('@') {
        Some(crate::compliance::normalise(address))
    } else {
        None
    }
}

/// Is this an address this app mails? Users first (an owner or teammate), then leads.
async fn owned_address(pool: &PgPool, address: &str) -> bool {
    if let Ok(Some(_)) = sqlx::query_scalar::<_, i64>(
        "SELECT 1::bigint FROM users WHERE lower(email) = lower($1) LIMIT 1",
    )
    .bind(address)
    .fetch_optional(pool)
    .await
    {
        return true;
    }
    sqlx::query_scalar::<_, i64>(
        "SELECT 1::bigint FROM leads WHERE lower(email) = lower($1) LIMIT 1",
    )
    .bind(address)
    .fetch_optional(pool)
    .await
    .ok()
    .flatten()
    .is_some()
}

/// GET /api/v1/settings/do-not-mail/webhook — the URL the operator pastes into the provider.
pub async fn webhook_url(State(state): State<AppState>, auth: AuthUser) -> Response {
    if !auth.is_admin {
        return refusal(
            StatusCode::FORBIDDEN,
            "only an operator can read the mail-events address",
        );
    }
    let token = match token(&state.pool).await {
        Ok(t) => t,
        Err(e) => {
            tracing::error!("could not read the mail-events token: {e}");
            return refusal(
                StatusCode::INTERNAL_SERVER_ERROR,
                "could not read the events token",
            );
        }
    };
    // WHEN the provider last reported something. The console shows this instead of asking a customer
    // to paste the address into a provider they do not control — the provider is ours, and the fleet
    // registers these three event types per sending domain. A read failure answers `null`, which the
    // screen words as "waiting for the first report" rather than as an error.
    let last_event_at = sqlx::query_scalar::<_, Option<String>>(
        "SELECT value ->> 'at' FROM admin_settings WHERE key = 'mail_events_last'",
    )
    .fetch_optional(&state.pool)
    .await
    .ok()
    .flatten();
    Json(json!({
        "url": format!("{APP_URL}/api/v1/webhooks/mailgun/events/{token}"),
        "events": ["permanent_fail", "complained", "unsubscribed"],
        "last_event_at": last_event_at,
    }))
    .into_response()
}
